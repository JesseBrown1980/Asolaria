#!/usr/bin/env node
/**
 * generate-connector-wrappers.js — Auto-generate ASO wrappers for all connectors.
 *
 * For each connector in src/connectors/ that lacks a -aso.js counterpart,
 * generates a wrapper that uses withAso from aso-connector-middleware to wrap
 * operational functions, and passes through everything else.
 *
 * Idempotent: skips connectors that already have a -aso.js file.
 */

const fs = require("fs");
const path = require("path");

const CONNECTORS_DIR = path.resolve(__dirname, "..", "src", "connectors");

// Patterns that indicate operational functions worth wrapping
const OP_PATTERNS = [
  /^run/, /^start/, /^stop/, /^get\w*Status/, /^publish/,
  /^send/, /^list/, /^create/, /^delete/, /^update/,
  /^sync/, /^connect/, /^disconnect/, /^init/, /^fetch/,
  /^execute/, /^invoke/, /^launch/, /^shutdown/, /^restart/,
  /^subscribe/, /^unsubscribe/, /^poll/, /^push/, /^pull/,
  /^upload/, /^download/, /^capture/, /^record/, /^mirror/,
  /^broadcast/, /^dispatch/, /^route/, /^forward/, /^relay/,
  /^spawn/, /^kill/, /^open/, /^close/, /^query/, /^search/,
  /^write/, /^read[A-Z]/, /^set[A-Z]/, /^check/, /^test/,
  /^audit/, /^scan/, /^rebuild/, /^boot/, /^load/, /^save/,
];

function isOperational(name) {
  return OP_PATTERNS.some((re) => re.test(name));
}

function extractConnectorName(filename) {
  // "fooBarConnector.js" -> base "fooBar", varName "fooBar"
  const base = filename.replace(/\.js$/, "");
  const short = base.replace(/Connector$/, "");
  return { base, short };
}

function generateWrapper(base, short, exportedFns, allKeys) {
  const wrappedFns = exportedFns.filter((fn) => isOperational(fn));
  const passthroughKeys = allKeys.filter((k) => !wrappedFns.includes(k));

  const lines = [];
  lines.push(`/**`);
  lines.push(` * ${base}-aso.js — Auto-generated ASO wrapper for ${base}.`);
  lines.push(` * Generated by tools/generate-connector-wrappers.js`);
  lines.push(` */`);
  lines.push(``);
  lines.push(`const original = require("./${base}");`);
  lines.push(`const { withAso } = require("../aso-connector-middleware");`);
  lines.push(``);

  if (wrappedFns.length > 0) {
    lines.push(`// --- Wrap operational functions with ASO telemetry ---`);
    for (const fn of wrappedFns) {
      lines.push(`const wrapped_${fn} = withAso("${short}", original.${fn});`);
    }
    lines.push(``);
  }

  lines.push(`// --- Re-export everything, replacing wrapped functions ---`);
  lines.push(`module.exports = {`);
  lines.push(`  ...original,`);
  for (const fn of wrappedFns) {
    lines.push(`  ${fn}: wrapped_${fn},`);
  }
  lines.push(`};`);
  lines.push(``);

  return { content: lines.join("\n"), wrappedCount: wrappedFns.length };
}

// --- Main ---
const files = fs.readdirSync(CONNECTORS_DIR).filter((f) => f.endsWith(".js") && !f.includes("-aso"));
const existingAso = new Set(
  fs.readdirSync(CONNECTORS_DIR).filter((f) => f.endsWith("-aso.js")).map((f) => f.replace("-aso.js", ".js"))
);

let generated = 0;
let skipped = 0;
const report = [];

for (const file of files) {
  const { base, short } = extractConnectorName(file);
  const asoFile = `${base}-aso.js`;

  if (existingAso.has(file)) {
    skipped++;
    continue;
  }

  // Load the original to inspect exports
  let mod;
  try {
    mod = require(path.join(CONNECTORS_DIR, file));
  } catch (e) {
    console.log(`  SKIP ${file} (load error: ${e.message.slice(0, 60)})`);
    skipped++;
    continue;
  }

  const allKeys = Object.keys(mod);
  const exportedFns = allKeys.filter((k) => typeof mod[k] === "function");

  const { content, wrappedCount } = generateWrapper(base, short, exportedFns, allKeys);

  fs.writeFileSync(path.join(CONNECTORS_DIR, asoFile), content, "utf-8");
  generated++;
  report.push({ connector: base, functions: exportedFns.length, wrapped: wrappedCount });
  console.log(`  GEN ${asoFile} — ${wrappedCount}/${exportedFns.length} functions wrapped`);
}

console.log(`\n=== Summary ===`);
console.log(`Generated: ${generated}`);
console.log(`Skipped (already exist): ${skipped}`);
console.log(`Total -aso.js files now: ${generated + existingAso.size}`);
if (report.length > 0) {
  const totalWrapped = report.reduce((s, r) => s + r.wrapped, 0);
  const totalFns = report.reduce((s, r) => s + r.functions, 0);
  console.log(`Total functions wrapped: ${totalWrapped}/${totalFns}`);
}
